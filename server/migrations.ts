import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type pg from 'pg';
import { transaction,type Queryable } from './db.js';

interface MigrationFile {name:string;sql:string;checksum:string;legacyChecksum:string}
const digest=(value:string)=>createHash('sha256').update(value).digest('hex');
export async function migrationFiles(directory=resolve('db/migrations')):Promise<MigrationFile[]> {
  const names=(await readdir(directory)).filter((name)=>/^\d+_[a-z_]+\.sql$/.test(name)).sort();
  return Promise.all(names.map(async(name)=>{
    const sql=(await readFile(resolve(directory,name),'utf8')).replace(/\r\n/g,'\n');
    return {name,sql,checksum:digest(sql),legacyChecksum:digest(sql.replace(/\n/g,'\r\n'))};
  }));
}
async function applyFiles(tx:Queryable,files:MigrationFile[]) {
  await tx.query('CREATE TABLE IF NOT EXISTS schema_migrations(name text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now())');
  for(const file of files) {
    const existing=(await tx.query('SELECT checksum FROM schema_migrations WHERE name=$1',[file.name])).rows[0];
    if(existing) {
      if(![file.checksum,file.legacyChecksum].includes(existing.checksum))throw new Error('MIGRATION_CHECKSUM_MISMATCH');
    } else {
      await tx.query(file.sql);await tx.query('INSERT INTO schema_migrations(name,checksum) VALUES($1,$2)',[file.name,file.checksum]);
    }
  }
}
async function verifyFiles(tx:Queryable,files:MigrationFile[]) {
  const applied=(await tx.query('SELECT name,checksum FROM public.schema_migrations ORDER BY name')).rows;
  if(applied.length!==files.length)throw new Error('CONTROLLED_MIGRATION_REQUIRED');
  for(const file of files) {
    const found=applied.find((row)=>row.name===file.name);
    if(!found||![file.checksum,file.legacyChecksum].includes(found.checksum))throw new Error('CONTROLLED_MIGRATION_REQUIRED');
  }
}
export const EMPTY_DATABASE_CHECK_SQL=`SELECT
    (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
     WHERE n.nspname !~ '^pg_' AND n.nspname<>'information_schema'
       AND c.relkind IN ('r','p','v','m','S','f')
       AND NOT EXISTS(SELECT 1 FROM pg_depend d WHERE d.classid='pg_class'::regclass AND d.objid=c.oid AND d.deptype='e'))+
    (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
     WHERE n.nspname !~ '^pg_' AND n.nspname<>'information_schema'
       AND NOT EXISTS(SELECT 1 FROM pg_depend d WHERE d.classid='pg_proc'::regclass AND d.objid=p.oid AND d.deptype='e')) AS count`;
export async function assertEmptyDatabase(tx:Queryable) {
  const objects=(await tx.query(EMPTY_DATABASE_CHECK_SQL)).rows[0];
  if(Number(objects.count)!==0)throw new Error('DATABASE_NOT_EMPTY');
}

export async function emptySchemaSql(directory=resolve('db/migrations')) {
  const files=await migrationFiles(directory);
  const header=`-- Generated by npm run db:schema. Structure/defaults only; no owner, sessions or business/demo data.\n-- Preferred import: INITIALIZE_EMPTY_DATABASE=true on first Coolify launch.\n-- Manual import requires private session settings skladno.expected_database and skladno.expected_role.\nBEGIN;\nSELECT pg_advisory_xact_lock(72904110);\nSET LOCAL search_path=public,pg_catalog;\nDO $guard$\nBEGIN\n  IF current_setting('skladno.expected_database',true) IS NULL OR current_setting('skladno.expected_role',true) IS NULL\n    OR current_database()<>current_setting('skladno.expected_database',true) OR current_user<>current_setting('skladno.expected_role',true) THEN\n    RAISE EXCEPTION 'DATABASE_IDENTITY_NOT_CONFIRMED';\n  END IF;\n  IF (${EMPTY_DATABASE_CHECK_SQL})<>0 THEN RAISE EXCEPTION 'DATABASE_NOT_EMPTY'; END IF;\nEND $guard$;\nCREATE TABLE schema_migrations(name text PRIMARY KEY,checksum text NOT NULL,applied_at timestamptz NOT NULL DEFAULT now());\n`;
  return header+files.map((file)=>`\n-- ${file.name}\n${file.sql}\nINSERT INTO schema_migrations(name,checksum) VALUES('${file.name}','${file.checksum}');\n`).join('')+'\nCOMMIT;\n';
}

export async function initializeEmptyDatabase(pool:pg.Pool,directory=resolve('db/migrations')) {
  const files=await migrationFiles(directory);
  return transaction(pool,async(tx)=>{
    await tx.query('SELECT pg_advisory_xact_lock(72904110)');
    await tx.query('SET LOCAL search_path=public,pg_catalog');
    const managed=(await tx.query("SELECT to_regclass('public.schema_migrations') IS NOT NULL AS exists")).rows[0].exists;
    if(managed){await verifyFiles(tx,files);return 'already-initialized' as const;}
    await assertEmptyDatabase(tx);await applyFiles(tx,files);
    return 'initialized' as const;
  });
}

export async function migrate(pool: pg.Pool, directory = resolve('db/migrations')) {
  const files = await migrationFiles(directory);
  await transaction(pool, async (tx) => {
    await tx.query('SELECT pg_advisory_xact_lock(72904110)');
    await tx.query('SET LOCAL search_path=public,pg_catalog');
    await applyFiles(tx,files);
  });
  return files.length;
}
